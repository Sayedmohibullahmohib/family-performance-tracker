import { readFileSync, writeFileSync } from "node:fs";
import vm from "node:vm";

const babelSource = readFileSync("static/vendor/babel.min.js", "utf8");
const appSource = readFileSync("static/app.jsx", "utf8");
const sandbox = {};

vm.createContext(sandbox);
vm.runInContext(babelSource, sandbox);

if (!sandbox.Babel?.transform) {
  throw new Error("Local Babel compiler could not be loaded.");
}

const result = sandbox.Babel.transform(appSource, {
  presets: ["env", "react"],
  plugins: ["transform-react-jsx"],
  sourceType: "script",
  comments: false,
  compact: false
});

const output = [
  "/* Generated by npm run build from static/app.jsx. Do not edit directly. */",
  result.code,
  ""
].join("\n");

writeFileSync("static/app.bundle.js", output);
console.log("Built static/app.bundle.js");
